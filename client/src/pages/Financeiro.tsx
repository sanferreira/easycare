function parseNumberInput(value: string): number {
  const normalized = value.replace(",", ".").trim();
  const parsed = Number(normalized);
  if (!Number.isFinite(parsed)) return 0;
  return Math.max(0, parsed);
}

function toCurrencyNumber(value: unknown): number {
  const parsed = Number(value ?? 0);
  if (!Number.isFinite(parsed)) return 0;
  return parsed;
}

async function parseApiJson<T>(res: Response, fallbackMessage: string): Promise<T> {
  const contentType = (res.headers.get("content-type") || "").toLowerCase();
  const raw = await res.text();
  const trimmed = raw.trim();

  const looksLikeJson =
    contentType.includes("application/json")
    || trimmed.startsWith("{")
    || trimmed.startsWith("[");

  let data: unknown = null;
  if (trimmed.length > 0) {
    if (!looksLikeJson) {
      if (trimmed.startsWith("<!DOCTYPE") || trimmed.startsWith("<html")) {
        throw new Error("Resposta HTML recebida da API. Reinicie/atualize o backend e confira o proxy.");
      }
      throw new Error(fallbackMessage);
    }
    try {
      data = JSON.parse(trimmed);
    } catch {
      throw new Error("Resposta JSON inválida da API.");
    }
  }

  if (!res.ok) {
    const message =
      typeof (data as { message?: unknown })?.message === "string"
        ? ((data as { message: string }).message.trim() || fallbackMessage)
        : fallbackMessage;
    throw new Error(message);
  }

  return data as T;
}

